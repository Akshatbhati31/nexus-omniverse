export function can(roleId: RoleId | undefined, permission: Permission, roles: RoleDefinition[] = ROLE_DEFINITIONS) {
  if (!roleId) return false
  return roles.some((role) => role.id === roleId && role.permissions.includes(permission))
}

export function getRole(roleId: RoleId, roles: RoleDefinition[] = ROLE_DEFINITIONS) {
  return roles.find((role) => role.id === roleId) ?? roles[roles.length - 1]
}
