const at = (minutesAgo: number) => new Date(DEMO_EPOCH - minutesAgo * 60_000).toISOString()

function timeline(prefix: string, _name: string, events: Array<[number, string, string, TimelineEvent['kind']]>): TimelineEvent[] {
  return events.map(([minutesAgo, title, detail, kind], index) => ({
    id: `${prefix}-evt-${index}`,
    at: at(minutesAgo),
    title,
    detail,
    kind,
  }))
}

function vital(label: string, value: number, unit: string, delta: number, format?: Vital['format']): Vital {
  return { label, value, unit, delta, format }
}

